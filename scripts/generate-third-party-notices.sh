#!/usr/bin/env bash
# Generate THIRD_PARTY_NOTICES (full license texts) and optional Apache NOTICE copies.
# Dependency set is the union across all release GOOS/GOARCH targets.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

GO_LICENSES_VERSION="v2.0.1"
GO_TOOLCHAIN="${GO_TOOLCHAIN:-go1.27.3}"
SCAN="./cmd/keep"

# Matches .goreleaser.yaml build matrix.
PLATFORMS=(
  "linux:amd64"
  "linux:arm64"
  "darwin:amd64"
  "darwin:arm64"
  "windows:amd64"
  "windows:arm64"
)

export GOTOOLCHAIN="$GO_TOOLCHAIN"
if ! command -v go-licenses >/dev/null 2>&1; then
  go install "github.com/google/go-licenses/v2@${GO_LICENSES_VERSION}"
fi
export PATH="$(go env GOPATH)/bin:$PATH"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

declare -A module_version=()
declare -A module_license=()

for plat in "${PLATFORMS[@]}"; do
  IFS=: read -r goos goarch <<<"$plat"
  export GOOS="$goos" GOARCH="$goarch"

  while IFS=, read -r pkg _ lic; do
    pkg="${pkg//\"/}"
    lic="${lic//\"/}"
    [[ -n "$pkg" ]] || continue
    module_license["$pkg"]="$lic"
  done < <(go-licenses csv "$SCAN")

  while read -r modver; do
    [[ -n "$modver" ]] || continue
    path="${modver%@*}"
    ver="${modver#*@}"
    module_version["$path"]="$ver"
  done < <(
    go list -deps -f '{{if and .Module (not .Standard)}}{{.Module.Path}}@{{.Module.Version}}{{end}}' "$SCAN" | sort -u
  )

  save_dir="$work/save/${goos}_${goarch}"
  go-licenses save --save_path="$save_dir" --force "$SCAN" >/dev/null

  while IFS= read -r abs; do
    rel="${abs#"$save_dir"/}"
    [[ -n "$rel" ]] || continue
    dest="$work/union/$rel"
    if [[ ! -e "$dest" ]]; then
      mkdir -p "$(dirname "$dest")"
      cp -a "$abs" "$dest"
    fi
  done < <(find "$save_dir" -type f \( -name 'LICENSE*' -o -name 'NOTICE' \))
done

mkdir -p third_party/apache-notices
find third_party/apache-notices -type f ! -name .gitkeep -delete 2>/dev/null || true

mapfile -t modules < <(printf '%s\n' "${!module_version[@]}" | sort)

{
  echo "Third-party notices for keep-cli"
  echo "Generated by scripts/generate-third-party-notices.sh"
  echo "Includes dependencies bundled in release builds for:"
  for plat in "${PLATFORMS[@]}"; do
    IFS=: read -r goos goarch <<<"$plat"
    echo "  ${goos}/${goarch}"
  done
  echo ""
} > THIRD_PARTY_NOTICES

find_license_file() {
  local dir="$1"
  local f
  for f in LICENSE LICENSE.txt LICENSE.md; do
    if [[ -f "$dir/$f" ]]; then
      echo "$dir/$f"
      return 0
    fi
  done
  return 1
}

for mod in "${modules[@]}"; do
  ver="${module_version[$mod]:-}"
  if [[ -z "$ver" ]]; then
    ver="(devel)"
  fi
  lic="${module_license[$mod]:-unknown}"
  dir="$work/union/$mod"
  if [[ "$mod" == "github.com/swtormy-agents/keep-cli" ]]; then
    dir="$ROOT"
  fi

  if ! lic_file="$(find_license_file "$dir")"; then
    echo "missing license file for $mod ($ver)" >&2
    exit 1
  fi

  {
    echo "================================================================================"
    echo "Module: ${mod} ${ver}"
    echo "License: ${lic}"
    echo "================================================================================"
    echo ""
    cat "$lic_file"
    echo ""
    echo ""
  } >> THIRD_PARTY_NOTICES

  if [[ "$lic" == "Apache-2.0" && -f "$dir/NOTICE" ]]; then
    safe="${mod//\//_}"
    safe="${safe//\./_}"
    cp "$dir/NOTICE" "third_party/apache-notices/${safe}.NOTICE"
  fi
done

echo "Wrote THIRD_PARTY_NOTICES ($(wc -l < THIRD_PARTY_NOTICES) lines) and third_party/apache-notices/"
